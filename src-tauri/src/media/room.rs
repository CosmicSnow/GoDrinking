fn accept_exact_answer_with_fence(
    json: &str,
    peer_ip: Option<IpAddr>,
    answers: &Arc<Mutex<Vec<ExactOfferAnswer>>>,
    offer_fences: &ExactOfferFences,
    expected: OfferEpochFence,
) -> Result<(), String> {
    let signal: PeerSignal = serde_json::from_str(json).map_err(|error| error.to_string())?;
    let id = signal
        .id
        .as_ref()
        .ok_or_else(|| "answer is missing viewer id".to_owned())?;
    if offer_fences
        .lock()
        .ok()
        .map(|fences| fences.get(id).copied() == Some(expected))
        .unwrap_or(false)
    {
        accept_exact_answer_with_fence_signal(signal, peer_ip, answers, expected)
    } else {
        Err("answer is for a stale or unknown offer".into())
    }
}

