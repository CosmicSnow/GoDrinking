/// Maps `ERR *` lines to the generic UI strings of UI.md: wrong Password and
/// unknown rooms are indistinguishable, and a banned IP gets the same answer.
/// The raw code is logged so the UI string can be traced.
fn protocol_error(code: &str) -> String {
    logger::log("ERROR", "golive2 err", &format!("ERR {code}"));
    match code {
        "FULL" => "This session is full.".into(),
        _ => "Could not join.".into(),
    }
}

pub fn submit_answer(host: SocketAddr, answer: &PeerSignal) -> Result<(), String> {
    let mut stream = TcpStream::connect_timeout(&host, Duration::from_secs(3))
        .map_err(|error| error.to_string())?;
    let body = serde_json::to_string(answer).map_err(|error| error.to_string())?;
    stream
        .write_all(format!("ANSWER {body}\n").as_bytes())
        .map_err(|error| error.to_string())?;
    stream.shutdown(std::net::Shutdown::Write).ok();
    Ok(())
}

pub(crate) fn submit_answer_exact(
    host: SocketAddr,
    answer: &PeerSignal,
    fence: OfferEpochFence,
) -> Result<(), String> {
    let mut stream = TcpStream::connect_timeout(&host, Duration::from_secs(3))
        .map_err(|error| error.to_string())?;
    let body = serde_json::to_string(&ExactAnswerEnvelope {
        signal: answer.clone(),
        fence,
    })
    .map_err(|error| error.to_string())?;
    stream
        .write_all(format!("ANSWER {body}\n").as_bytes())
        .map_err(|error| error.to_string())?;
    stream.shutdown(std::net::Shutdown::Write).ok();
    Ok(())
}

