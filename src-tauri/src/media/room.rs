fn udp_loop(
    code: Arc<Mutex<String>>,
    tcp_port: u16,
    shutdown: Arc<AtomicBool>,
    ingress: IngressGate,
) {
    let Ok(socket) = UdpSocket::bind(("0.0.0.0", DISCOVERY_PORT)) else {
        return;
    };
    let _ = socket.set_read_timeout(Some(Duration::from_millis(200)));
    let mut buffer = [0_u8; 256];
    while !shutdown.load(Ordering::Acquire) {
        let Ok((size, from)) = socket.recv_from(&mut buffer) else {
            continue;
        };
        let request = String::from_utf8_lossy(&buffer[..size]);
        if !ingress.is_active() {
            continue;
        }
        let current = code.lock().map(|code| code.clone()).unwrap_or_default();
        if let Some(reply) = udp_reply(&request, &current, tcp_port) {
            let _ = socket.send_to(reply.as_bytes(), from);
        }
    }
}

/// Matches a `GOLIVE1 FIND <code>` discovery request against the current
/// Room code. Returns the `GOLIVE1 HOST <code> <port>` reply, or None.
fn udp_reply(request: &str, code: &str, tcp_port: u16) -> Option<String> {
    let mut parts = request.split_whitespace();
    if parts.next() != Some(std::str::from_utf8(DISCOVERY_MAGIC).unwrap_or("GOLIVE1")) {
        return None;
    }
    if parts.next() != Some("FIND") {
        return None;
    }
    if parts.next() != Some(code) {
        return None;
    }
    Some(format!("GOLIVE1 HOST {code} {tcp_port}"))
}

pub fn discover_room(
    code: &str,
    password: &str,
    nickname: &str,
) -> Result<(SocketAddr, PeerSignal, String), String> {
    let host = discover_host(code, nickname)?;
    let (offer, host_nickname) = fetch_offer(host, password, nickname)?;
    Ok((host, offer, host_nickname))
}

fn discover_host(code: &str, nickname: &str) -> Result<SocketAddr, String> {
    logger::begin_session("viewer", "lan");
    logger::log(
        "INFO",
        "lan find",
        &format!("code={code} nickname={nickname}"),
    );
    let socket = UdpSocket::bind("0.0.0.0:0").map_err(|error| error.to_string())?;
    socket
        .set_broadcast(true)
        .map_err(|error| error.to_string())?;
    socket
        .set_read_timeout(Some(Duration::from_secs(2)))
        .map_err(|error| error.to_string())?;
    let query = format!("GOLIVE1 FIND {code}");
    socket
        .send_to(query.as_bytes(), ("255.255.255.255", DISCOVERY_PORT))
        .map_err(|error| {
            logger::log("ERROR", "lan find", &format!("broadcast failed: {error}"));
            error.to_string()
        })?;
    let mut buffer = [0_u8; 256];
    let (size, from) = socket.recv_from(&mut buffer).map_err(|_| {
        logger::log(
            "ERROR",
            "lan find",
            "no host answered (room not found on this network)",
        );
        "room was not found on this network".to_owned()
    })?;
    let reply = String::from_utf8_lossy(&buffer[..size]);
    let mut parts = reply.split_whitespace();
    if parts.next() != Some("GOLIVE1") || parts.next() != Some("HOST") {
        logger::log("ERROR", "lan find", &format!("invalid reply: {reply}"));
        return Err("invalid room discovery reply".into());
    }
    if parts.next() != Some(code) {
        logger::log(
            "ERROR",
            "lan find",
            &format!("code mismatch in reply: {reply}"),
        );
        return Err("room code mismatch".into());
    }
    let port = parts
        .next()
        .and_then(|value| value.parse::<u16>().ok())
        .ok_or_else(|| {
            logger::log("ERROR", "lan find", &format!("reply missing port: {reply}"));
            "room reply is missing a port".to_owned()
        })?;
    let host = SocketAddr::new(from.ip(), port);
    logger::log("INFO", "lan find", &format!("host found at {host}"));
    Ok(host)
}

