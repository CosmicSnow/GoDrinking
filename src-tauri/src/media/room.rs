/// GOLIVE2 Viewer handshake: `HELLO GOLIVE2` / `AUTH` / `NICK`, then wait for
/// `OK`/`PENDING` and finally `OFFER <json>`. With Admission on the Host may
/// keep us waiting up to 60s before deciding; the stream stays open. Returns
/// the offer plus the Host's Nickname (empty when the Host sent none).
pub(crate) fn fetch_offer(
    host: SocketAddr,
    password: &str,
    nickname: &str,
) -> Result<(PeerSignal, String), String> {
    let (signal, _, host_nickname) = fetch_offer_with_identity(host, password, nickname)?;
    Ok((signal, host_nickname))
}

pub(crate) fn fetch_offer_exact(
    host: SocketAddr,
    password: &str,
    nickname: &str,
) -> Result<(ExactOffer, String), String> {
    let (signal, fence, host_nickname) = fetch_offer_with_identity(host, password, nickname)?;
    let fence =
        fence.ok_or_else(|| "host returned a legacy offer without an exact fence".to_owned())?;
    Ok((ExactOffer { signal, fence }, host_nickname))
}

fn fetch_offer_with_identity(
    host: SocketAddr,
    password: &str,
    nickname: &str,
) -> Result<(PeerSignal, Option<OfferEpochFence>, String), String> {
    logger::log("INFO", "golive2", &format!("connect {host}"));
    let mut stream = TcpStream::connect_timeout(&host, Duration::from_secs(8))
        .map_err(|error| format!("connect: {error}"))?;
    stream
        .set_read_timeout(Some(PENDING_READ_TIMEOUT))
        .map_err(|error| error.to_string())?;
    stream
        .write_all(b"HELLO GOLIVE2\n")
        .map_err(|error| error.to_string())?;
    if password.is_empty() {
        stream
            .write_all(b"AUTH\n")
            .map_err(|error| error.to_string())?;
    } else {
        stream
            .write_all(format!("AUTH {password}\n").as_bytes())
            .map_err(|error| error.to_string())?;
    }
    stream
        .write_all(format!("NICK {nickname}\n").as_bytes())
        .map_err(|error| error.to_string())?;
    logger::log("INFO", "golive2", "sent HELLO GOLIVE2 / AUTH / NICK");
    let mut reader = BufReader::new(stream);
    let mut host_nickname = String::new();
    loop {
        let mut line = String::new();
        if reader
            .read_line(&mut line)
            .map_err(|error| error.to_string())?
            == 0
        {
            logger::log("WARN", "golive2", "host closed the connection");
            return Err("host closed the connection".into());
        }
        let line = line.trim_end();
        if let Some(json) = line.strip_prefix("OFFER ") {
            logger::log("INFO", "golive2", "received OFFER");
            if let Ok(envelope) = serde_json::from_str::<ExactOfferEnvelope>(json) {
                return Ok((envelope.signal, Some(envelope.fence), host_nickname));
            }
            let signal = serde_json::from_str(json).map_err(|error| error.to_string())?;
            return Ok((signal, None, host_nickname));
        }
        if let Some(name) = line.strip_prefix("HOSTNICK ") {
            host_nickname = name.to_owned();
            continue;
        }
        if line == "REJECT" {
            logger::log("WARN", "golive2", "received REJECT (host declined)");
            return Err("The host declined.".into());
        }
        if line == "PENDING" || line.starts_with("PENDING ") {
            logger::log("INFO", "golive2", "received PENDING (waiting for the host)");
            continue;
        }
        if line == "OK" || line.starts_with("OK ") {
            logger::log("INFO", "golive2", "received OK");
            continue;
        }
        if let Some(error) = line.strip_prefix("ERR ") {
            return Err(protocol_error(error));
        }
    }
}

/// Direct join: no UDP discovery, straight GOLIVE2 TCP to the address the
/// Host shared. TCP failures map to the UI string of UI.md.
pub fn discover_direct(
    host: SocketAddr,
    password: &str,
    nickname: &str,
) -> Result<(PeerSignal, String), String> {
    logger::begin_session("viewer", "direct");
    logger::log(
        "INFO",
        "direct connect",
        &format!("host={host} nickname={nickname}"),
    );
    fetch_offer(host, password, nickname).map_err(|error| {
        if error.starts_with("connect: ") {
            logger::log("ERROR", "direct connect", &error);
            "Could not reach that address.".into()
        } else {
            error
        }
    })
}

