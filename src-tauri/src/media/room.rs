/// Mints a fresh offer for one Viewer. The id is generated by the TCP
/// handler (it is announced in `PENDING`/`OK` before the offer exists) and
/// the nickname comes from the `NICK` line.
pub(crate) type OfferMint =
    Arc<dyn Fn(&str, &str) -> Result<FencedPeerSignal, String> + Send + Sync>;
type OfferFences = Arc<Mutex<HashMap<String, EpochFence>>>;
type ExactOfferFences = Arc<Mutex<HashMap<String, OfferEpochFence>>>;

enum ProducedOffer {
    Legacy(FencedPeerSignal),
    Exact(ExactOffer),
}

type OfferProducer = Arc<dyn Fn(&str, &str) -> Result<ProducedOffer, String> + Send + Sync>;

fn legacy_offer_producer(mint: OfferMint) -> OfferProducer {
    Arc::new(move |id, nickname| mint(id, nickname).map(ProducedOffer::Legacy))
}

fn exact_offer_producer(mint: ExactOfferMint) -> OfferProducer {
    Arc::new(move |id, nickname| mint(id, nickname).map(ProducedOffer::Exact))
}

/// Exact offer result used by the post-actor integration path. The attempt
/// identity is never reconstructed from a Viewer ID or mailbox drain state.
#[derive(Clone, Debug)]
pub(crate) struct ExactOffer {
    pub(crate) signal: PeerSignal,
    pub(crate) fence: OfferEpochFence,
}

pub(crate) type ExactOfferMint =
    Arc<dyn Fn(&str, &str) -> Result<ExactOffer, String> + Send + Sync>;

#[derive(Clone, Debug)]
pub(crate) struct ExactOfferAnswer {
    pub(crate) signal: PeerSignal,
    pub(crate) fence: OfferEpochFence,
}

/// Redacted one-line summary of an exact offer fence for correlated
/// diagnostics: Session/Share/Link/attempt IDs only. Never includes
/// Passwords, Tokens, SDP payloads, or nicknames.
pub(crate) fn offer_fence_summary(fence: &OfferEpochFence) -> String {
    let link = fence
        .epoch
        .link
        .map(|link| format!("{link:?}"))
        .unwrap_or_else(|| "none".into());
    format!(
        "session={:?} share={:?} link={link} attempt={:?}",
        fence.epoch.session, fence.epoch.share, fence.attempt,
    )
}

#[derive(Clone)]
pub(crate) struct IngressGate {
    active: Arc<AtomicBool>,
}

impl IngressGate {
    pub(crate) fn active() -> Self {
        Self {
            active: Arc::new(AtomicBool::new(true)),
        }
    }

    pub(crate) fn inactive() -> Self {
        Self {
            active: Arc::new(AtomicBool::new(false)),
        }
    }

    pub(crate) fn activate(&self) {
        self.active.store(true, Ordering::Release);
    }

    pub(crate) fn deactivate(&self) {
        self.active.store(false, Ordering::Release);
    }

    pub(crate) fn is_active(&self) -> bool {
        self.active.load(Ordering::Acquire)
    }
}

/// Reports how many Viewers are currently Connected on the engine side, so
/// the room can enforce the 8+8 cap before admitting a new Pending.
pub(crate) type ViewerCount = Arc<dyn Fn() -> usize + Send + Sync>;

pub(crate) struct LanRoom {
    /// Current Room code. Mutable so the Host can rotate it live (PRD-18);
    /// the UDP loop reads it on every discovery request.
    code: Arc<Mutex<String>>,
    pub(crate) port: u16,
    answers: Arc<Mutex<Vec<FencedPeerSignal>>>,
    exact_answers: Arc<Mutex<Vec<ExactOfferAnswer>>>,
    exact_offer_fences: ExactOfferFences,
    shutdown: Arc<AtomicBool>,
    ingress: IngressGate,
    workers: Vec<(&'static str, JoinHandle<()>)>,
    connection_workers: ConnectionWorkers,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ShutdownStatus {
    pub(crate) quiesced: bool,
    pub(crate) pending: Vec<&'static str>,
    pub(crate) errors: Vec<String>,
}

impl LanRoom {
    pub(crate) fn start(
        mint: OfferMint,
        gate: Arc<SessionGate>,
        viewer_count: ViewerCount,
        host_nickname: String,
    ) -> Result<Self, String> {
        Self::start_with_producer(
            legacy_offer_producer(mint),
            gate,
            viewer_count,
            host_nickname,
            IngressGate::active(),
        )
    }

    fn start_with_producer(
        producer: OfferProducer,
        gate: Arc<SessionGate>,
        viewer_count: ViewerCount,
        host_nickname: String,
        ingress: IngressGate,
    ) -> Result<Self, String> {
        let code = Arc::new(Mutex::new(random_code()));
        let listener = TcpListener::bind("0.0.0.0:0").map_err(|error| error.to_string())?;
        listener
            .set_nonblocking(true)
            .map_err(|error| error.to_string())?;
        let port = listener
            .local_addr()
            .map_err(|error| error.to_string())?
            .port();
        let answers = Arc::new(Mutex::new(Vec::new()));
        let exact_answers = Arc::new(Mutex::new(Vec::new()));
        let offer_fences = Arc::new(Mutex::new(HashMap::new()));
        let exact_offer_fences = Arc::new(Mutex::new(HashMap::new()));
        let connection_workers = Arc::new(Mutex::new(Vec::new()));
        let shutdown = Arc::new(AtomicBool::new(false));
        let tcp_answers = Arc::clone(&answers);
        let tcp_exact_answers = Arc::clone(&exact_answers);
        let tcp_offer_fences = Arc::clone(&offer_fences);
        let tcp_exact_offer_fences = Arc::clone(&exact_offer_fences);
        let tcp_connections = Arc::clone(&connection_workers);
        let tcp_shutdown = Arc::clone(&shutdown);
        let tcp_ingress = ingress.clone();
        let tcp = thread::Builder::new()
            .name("godrinking-room-tcp".into())
            .spawn(move || {
                tcp_loop(
                    listener,
                    producer,
                    gate,
                    viewer_count,
                    tcp_answers,
                    tcp_exact_answers,
                    tcp_offer_fences,
                    tcp_exact_offer_fences,
                    tcp_connections,
                    tcp_shutdown,
                    host_nickname,
                    tcp_ingress,
                )
            })
            .map_err(|error| error.to_string())?;
        let udp_code = Arc::clone(&code);
        let udp_shutdown = Arc::clone(&shutdown);
        let udp_ingress = ingress.clone();
        let udp = thread::Builder::new()
            .name("godrinking-room-udp".into())
            .spawn(move || udp_loop(udp_code, port, udp_shutdown, udp_ingress))
            .map_err(|error| error.to_string())?;
        Ok(Self {
            code,
            port,
            answers,
            exact_answers,
            exact_offer_fences,
            shutdown,
            ingress,
            workers: vec![("LAN TCP worker", tcp), ("LAN UDP worker", udp)],
            connection_workers,
        })
    }

    pub(crate) fn take_answers(&self) -> Vec<FencedPeerSignal> {
        self.answers
            .lock()
            .map(|mut answers| std::mem::take(&mut *answers))
            .unwrap_or_default()
    }

    pub(crate) fn take_exact_answers(&self) -> Vec<ExactOfferAnswer> {
        self.exact_answers
            .lock()
            .map(|mut answers| std::mem::take(&mut *answers))
            .unwrap_or_default()
    }

    /// Creates a non-advertising LAN service for the later actor commit.
    pub(crate) fn start_inactive(
        mint: ExactOfferMint,
        gate: Arc<SessionGate>,
        viewer_count: ViewerCount,
        host_nickname: String,
    ) -> Result<Self, String> {
        Self::start_with_producer(
            exact_offer_producer(mint),
            gate,
            viewer_count,
            host_nickname,
            IngressGate::inactive(),
        )
    }

    pub(crate) fn activate(&self) {
        self.ingress.activate();
    }

    pub(crate) fn deactivate(&self) {
        self.ingress.deactivate();
    }

    pub(crate) fn ingress_active(&self) -> bool {
        self.ingress.is_active()
    }

    pub(crate) fn code(&self) -> String {
        self.code
            .lock()
            .map(|code| code.clone())
            .unwrap_or_default()
    }

    pub(crate) fn addresses() -> Vec<String> {
        local_addresses()
    }

    /// Stops LAN discovery/signaling and joins the accept, discovery, and all
    /// accepted-connection workers. Pending connections remain owned for a
    /// later retry instead of being detached and reported as stopped.
    pub(crate) fn shutdown_and_join(&mut self, timeout: Duration) -> ShutdownStatus {
        shutdown_room_workers(
            &self.shutdown,
            &mut self.workers,
            &self.connection_workers,
            timeout,
        )
    }
}

impl Drop for LanRoom {
    fn drop(&mut self) {
        let status = self.shutdown_and_join(Duration::from_secs(3));
        if !status.quiesced {
            eprintln!("[goDrinking] LAN cleanup incomplete: {status:?}");
        }
    }
}

